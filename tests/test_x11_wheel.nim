when defined(linux):
  import
    std/[os, osproc, streams, strutils],
    windy,
    windy/platforms/linux/x11/[x, xevent, xlib]

  type XWindow = x.Window

  const
    WindowTitle = "Windy X11 wheel regression"
    WheelUp = 4.cuint
    WheelDown = 5.cuint
    WheelLeft = 6.cuint
    WheelRight = 7.cuint
    WheelDelta = 10'f32

  proc queryTree(display: Display, window: XWindow, root, parent: ptr XWindow,
      children: ptr ptr UncheckedArray[XWindow], count: ptr cuint): cint
      {.cdecl, importc: "XQueryTree", dynlib: libX11.}
  proc fetchName(display: Display, window: XWindow, name: ptr cstring): cint
      {.cdecl, importc: "XFetchName", dynlib: libX11.}
  proc sendEvent(display: Display, window: XWindow, propagate: cint, mask: clong,
      event: ptr XEvent): cint {.cdecl, importc: "XSendEvent", dynlib: libX11.}
  proc closeDisplay(display: Display): cint
      {.cdecl, importc: "XCloseDisplay", dynlib: libX11.}
  proc sync(display: Display, discardEvents: cint): cint
      {.cdecl, importc: "XSync", dynlib: libX11.}

  proc findWindow(display: Display): XWindow =
    ## Locate only the newly created Windy window on the isolated X server.
    var
      root, parent: XWindow
      children: ptr UncheckedArray[XWindow]
      count: cuint
    doAssert queryTree(display, display.defaultRootWindow, addr root, addr parent,
      addr children, addr count) != 0
    defer:
      if children != nil: XFree(children)
    for index in 0 ..< count.int:
      var name: cstring
      if fetchName(display, children[index], addr name) != 0 and name != nil:
        let matches = $name == WindowTitle
        XFree(name)
        if matches: return children[index]
    raise newException(AssertionDefect, "Regression window was not created.")

  proc wheel(display: Display, window: XWindow, button: cuint, pressed: bool) =
    ## Queue one authentic X11 wheel edge for Windy's public callback path.
    var event = XEvent(button: XButtonEvent(
      kind: if pressed: xeButtonPress else: xeButtonRelease,
      display: display, window: window, root: display.defaultRootWindow,
      button: button, same_screen: 1))
    doAssert sendEvent(display, window, 0, if pressed: 4 else: 8, addr event) != 0

  proc main() =
    ## Verify press-only callbacks and accumulated deltas through actual X11 events.
    let
      executable = findExe("Xvfb")
      previousDisplay = getEnv("DISPLAY")
    doAssert executable.len > 0, "Xvfb is required; this test never uses the desktop display."
    let server = startProcess(executable, args = ["-displayfd", "1", "-screen", "0",
      "320x240x24", "-nolisten", "tcp"], options = {})
    defer:
      if server.running: server.terminate()
      discard server.waitForExit(5000)
      server.close()
    defer: putEnv("DISPLAY", previousDisplay)
    let number = server.outputStream.readLine().strip()
    doAssert number.len > 0 and number.allCharsInSet({'0' .. '9'})
    let name = ":" & number
    putEnv("DISPLAY", name)
    let window = newWindow(WindowTitle, ivec2(64, 64), vsync = false)
    defer: window.close()
    let display = XOpenDisplay(name.cstring)
    doAssert display != nil
    defer: discard closeDisplay(display)
    let handle = findWindow(display)
    var calls = 0
    window.onScroll = proc() =
      ## Count only public scroll callbacks generated by the event dispatcher.
      inc calls
    pollEvents()
    for (button, expected) in [(WheelUp, vec2(0, -WheelDelta)),
        (WheelDown, vec2(0, WheelDelta)), (WheelLeft, vec2(-WheelDelta, 0)),
        (WheelRight, vec2(WheelDelta, 0))]:
      calls = 0
      display.wheel(handle, button, true)
      discard sync(display, 0)
      pollEvents()
      doAssert calls == 1, "Each wheel press must emit one callback."
      doAssert window.scrollDelta == expected
      display.wheel(handle, button, false)
      discard sync(display, 0)
      pollEvents()
      doAssert calls == 1, "Wheel release must not emit another callback."
      doAssert window.scrollDelta == vec2(0, 0)
    calls = 0
    for gesture in 0 ..< 2:
      display.wheel(handle, WheelUp, true)
      display.wheel(handle, WheelUp, false)
    discard sync(display, 0)
    pollEvents()
    doAssert calls == 2, "Two wheel gestures must emit exactly two callbacks."
    doAssert window.scrollDelta == vec2(0, -2 * WheelDelta),
      "Multiple presses in one poll must accumulate their scroll deltas."
    pollEvents()
    doAssert window.scrollDelta == vec2(0, 0)
    echo "Windy X11 wheel: four directions, press-only callbacks, release suppression, batched accumulation, and per-frame reset passed."

  main()
else:
  echo "Windy X11 wheel regression is Linux-only."
